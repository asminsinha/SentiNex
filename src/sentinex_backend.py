    def detect_live_environment(self):
        """Checks whether Ryu Controller or Mininet is actively running on localhost/WSL."""
        import socket
        import urllib.request
        # Test Ryu OpenFlow port 6653 or 6633
        ryu_active = False
        for port in [6653, 6633]:
            try:
                s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
                s.settimeout(0.2)
                res = s.connect_ex(('127.0.0.1', port))
                s.close()
                if res == 0:
                    ryu_active = True
                    break
            except Exception:
                pass

        # Test Ryu REST API port 8080 and query switches
        ryu_rest_active = False
        live_dpids = []
        try:
            req = urllib.request.Request("http://127.0.0.1:8080/stats/switches", headers={'User-Agent': 'SentiNex'})
            with urllib.request.urlopen(req, timeout=0.8) as response:
                if response.status == 200:
                    ryu_rest_active = True
                    live_dpids = json.loads(response.read().decode())
        except Exception:
            pass

        # Test Mininet REST daemon port 8081
        mininet_daemon_active = False
        mininet_hosts_count = 0
        try:
            req_mn = urllib.request.Request("http://127.0.0.1:8081/status", headers={'User-Agent': 'SentiNex'})
            with urllib.request.urlopen(req_mn, timeout=0.8) as response:
                if response.status == 200:
                    mn_info = json.loads(response.read().decode())
                    if mn_info.get('running'):
                        mininet_daemon_active = True
                        mininet_hosts_count = mn_info.get('host_count', 0)
        except Exception:
            pass

        self.controller_connected = ryu_active or ryu_rest_active
        if ryu_rest_active and live_dpids:
            self.controller_type = f"Ryu OpenFlow 1.3 (Connected: {len(live_dpids)} Switches)"
            self.controller_host = "127.0.0.1:6653 (OFP) / 127.0.0.1:8080 (REST)"
        elif ryu_active or ryu_rest_active:
            self.controller_type = "Ryu OpenFlow 1.3 (Ready, 0 Switches)"
            self.controller_host = "127.0.0.1:6653 (OFP) / 127.0.0.1:8080 (REST)"
        else:
            self.controller_type = "Offline / Disconnected (Ryu Not Running)"
            self.controller_host = "Disconnected"

        # Update verified instantiated hosts if in Mininet mode
        if self.execution_mode == "mininet":
            self.instantiated_mininet_hosts = mininet_hosts_count

        return {
            'controller_connected': self.controller_connected,
            'controller_type': self.controller_type,
            'controller_host': self.controller_host,
            'ryu_of_port_active': ryu_active,
            'ryu_rest_port_active': ryu_rest_active,
            'live_dpids': live_dpids,
            'mininet_daemon_active': mininet_daemon_active,
            'mininet_running': mininet_daemon_active and (mininet_hosts_count > 0),
            'verified_mininet_hosts': mininet_hosts_count
        }

    def rebuild_topology(self, topo_type="linear", host_count=4, mode="emulation", threat_ratio=0.5, seed=42):
        """
        Dynamically builds/reconfigures the network topology.
        Supports 'linear', 'tree', 'star', and 'mesh'.
        Scales up to 1000+ logical hosts safely.
        """
        with self.lock:
            # Enforce limits
            host_count = max(2, min(int(host_count), 2000))
            threat_ratio = max(0.0, min(float(threat_ratio), 1.0))
            self.topo_type = topo_type
            self.configured_host_count = host_count
            self.execution_mode = mode
            self.threat_ratio = threat_ratio
            self.random_seed = seed

            rng = random.Random(seed)

            # Determine switch count based on topology type
            if topo_type == "star":
                num_switches = 1
            elif topo_type == "tree":
                # 1 root + 2 to 6 aggregation switches
                num_switches = max(2, min(8, 1 + (host_count + 3) // 4))
            elif topo_type == "mesh":
                num_switches = max(4, min(8, 2 + (host_count + 5) // 6))
            else:  # linear
                num_switches = max(2, min(10, (host_count + 3) // 4))

            # Build Switches
            self.switches = {}
            for i in range(1, num_switches + 1):
                dpid = i
                sw_id = f"s{dpid}"
                self.switches[sw_id] = {
                    'id': sw_id,
                    'dpid': dpid,
                    'label': f"SDN Switch {sw_id.upper()}",
                    'ports': [],
                    'status': 'active',
                    'flow_count': 1  # Initially table-miss rule
                }

            # Build Switch Links
            self.links = []
            switch_keys = list(self.switches.keys())
            if topo_type == "star":
                pass
            elif topo_type == "tree":
                root = switch_keys[0]
                for sw in switch_keys[1:]:
                    self.links.append({'source': root, 'target': sw, 'type': 'switch-switch', 'bandwidth': '10Gbps'})
            elif topo_type == "mesh":
                # Connect core switches to each other, plus edges
                for i in range(len(switch_keys)):
                    for j in range(i + 1, min(i + 3, len(switch_keys))):
                        self.links.append({'source': switch_keys[i], 'target': switch_keys[j], 'type': 'switch-switch', 'bandwidth': '10Gbps'})
            else:  # linear
                for i in range(len(switch_keys) - 1):
                    self.links.append({'source': switch_keys[i], 'target': switch_keys[i+1], 'type': 'switch-switch', 'bandwidth': '10Gbps'})

            # Build Hosts
            self.hosts = {}
            # Designate threat hosts deterministically if seed provided
            all_indices = list(range(1, host_count + 1))
            rng.shuffle(all_indices)
            num_threats = int(round(host_count * threat_ratio))
            threat_indices = set(all_indices[:num_threats])

            # Ensure host 1 is benign victim/generator and host 2 is target server for baseline compatibility
            if 1 in threat_indices and 2 in threat_indices:
                threat_indices.remove(1)

            for i in range(1, host_count + 1):
                hid = f"h{i}"
                ip = f"10.0.{i // 254}.{(i % 254) + 1}"
                mac = f"00:00:00:{i >> 16 & 0xff:02x}:{i >> 8 & 0xff:02x}:{i & 0xff:02x}"

                # Assign host to switch in round-robin
                assigned_sw = switch_keys[(i - 1) % num_switches]

                # Role designation for traffic generator
                is_threat_role = (i in threat_indices)
                if i == 2:
                    role = "Target Server / Victim"
                    designated_behavior = "benign_target"
                elif i == 1:
                    role = "Benign Web Client"
                    designated_behavior = "benign"
                elif is_threat_role:
                    # Alternate between DoS and Port Scan
                    designated_behavior = "dos" if (i % 2 == 1) else "scan"
                    role = "DoS SYN Attacker" if designated_behavior == "dos" else "Reconnaissance Scanner"
                else:
                    role = "Normal Client"
                    designated_behavior = "benign"

                # Check if this IP is currently blocked by the engine
                is_blocked = ip in self.sentinex_app.blocked_ips
                state = "blocked" if is_blocked else "benign"

                self.hosts[hid] = {
                    'id': hid,
                    'ip': ip,
                    'mac': mac,
                    'switch': assigned_sw,
                    'role': role,
                    'designated_behavior': designated_behavior,
                    'state': state,  # 'benign', 'suspicious', 'threat_detected', 'blocked', 'mitigation_failed', 'recovering'
                    'packets_sent': 0,
                    'last_seen': time.time()
                }

                self.links.append({'source': hid, 'target': assigned_sw, 'type': 'host-switch', 'bandwidth': '1Gbps'})

            # Initialize OpenFlow Flow Tables for each switch
            self.flow_tables = {}
            for sw_id, sw_info in self.switches.items():
                dpid = sw_info['dpid']
                self.flow_tables[dpid] = [
                    {
                        'table_id': 0,
                        'priority': 0,
                        'match': {'eth_type': '*', 'ipv4_src': '*', 'ipv4_dst': '*'},
                        'actions': ['CONTROLLER:OFPCML_NO_BUFFER'],
                        'idle_timeout': 0,
                        'hard_timeout': 0,
                        'packet_count': 0,
                        'byte_count': 0,
                        'rule_type': 'table_miss',
                        'installed_at': datetime.now().strftime("%H:%M:%S")
                    }
                ]

            # Re-install block rules if any IPs are in blocked_ips
            for ip in self.sentinex_app.blocked_ips:
                self._install_flow_drop_rule(ip)

            # Real Mininet Daemon Verification and Configuration
            if mode == "mininet":
                if host_count > 64:
                    self.instantiated_mininet_hosts = 0
                    self.execution_mode = "emulation"
                    mode_note = "Host count exceeds Mininet OS interface limit (max 64). Switched to Scalable Logical Emulation Mode."
                else:
                    # Attempt to invoke real Mininet instantiation on WSL daemon
                    try:
                        import urllib.request
                        req_data = json.dumps({'topo_type': topo_type, 'host_count': host_count}).encode('utf-8')
                        req_mn = urllib.request.Request(
                            "http://127.0.0.1:8081/start",
                            data=req_data,
                            headers={'Content-Type': 'application/json', 'User-Agent': 'SentiNex'}
                        )
                        with urllib.request.urlopen(req_mn, timeout=3.0) as resp:
                            if resp.status == 200:
                                res_json = json.loads(resp.read().decode())
                                self.instantiated_mininet_hosts = int(res_json.get('host_count', host_count))
                                self.execution_mode = "mininet"
                                mode_note = f"Real Mininet active in WSL2: {self.instantiated_mininet_hosts} hosts and {res_json.get('switch_count', len(self.switches))} switches."
                            else:
                                self.instantiated_mininet_hosts = 0
                                self.execution_mode = "emulation"
                                mode_note = f"Mininet daemon returned error {resp.status}. Switched to Logical Emulation."
                    except Exception as e:
                        # Mininet daemon not running or WSL offline
                        self.instantiated_mininet_hosts = 0
                        self.execution_mode = "emulation"
                        mode_note = f"Real Mininet daemon offline ({e}). Switched to Scalable Logical Emulation Mode."
            else:
                # User chose emulation mode
                was_mininet = (self.execution_mode == "mininet")
                self.instantiated_mininet_hosts = 0
                self.execution_mode = "emulation"
                mode_note = f"Scalable Logical Emulation active for {host_count} hosts."
                if was_mininet:
                    try:
                        import urllib.request
                        req_stop = urllib.request.Request("http://127.0.0.1:8081/stop", data=b'{}', headers={'Content-Type': 'application/json'})
                        urllib.request.urlopen(req_stop, timeout=0.3)
                    except Exception:
                        pass

            # Broadcast topology update event
            self._broadcast_event({
                'type': 'topology_rebuilt',
                'timestamp': time.time(),
                'iso_time': datetime.now().isoformat(),
                'topo_type': self.topo_type,
                'host_count': self.configured_host_count,
                'switch_count': len(self.switches),
                'link_count': len(self.links),
                'mode': self.execution_mode,
                'instantiated_mininet_hosts': self.instantiated_mininet_hosts,
                'threat_ratio': self.threat_ratio,
                'note': mode_note
            })

            return self.get_topology_summary()

