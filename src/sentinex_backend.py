    def set_model(self, model_name):
        """
        Dynamically switches active ML model between Random Forest ('rf')
        and Deep Learning Neural Network ('mlp') without restarting the server.
        """
        model_name = str(model_name).lower().strip()
        if model_name not in ['rf', 'mlp']:
            raise ValueError(f"Unsupported model: {model_name}. Supported: 'rf' or 'mlp'")

        with self.lock:
            if model_name == self.model_name:
                return {'success': True, 'model': self.model_name.upper(), 'message': f"Model is already {self.model_name.upper()}"}

            print(f"[*] Dynamically switching SentiNex detection backend to: {model_name.upper()}...")
            old_model = self.model_name.upper()
            self.sentinex_app = SentiNexRyuApp(model_name=model_name)
            self.extractor = self.sentinex_app.extractor
            self.flow_tracker = self.sentinex_app.flow_tracker
            self.xai = self.sentinex_app.xai
            self.model_name = self.sentinex_app.model_name

            event_obj = {
                'type': 'model_switched',
                'timestamp': time.time(),
                'emitted_at': time.time(),
                'iso_time': datetime.now().strftime("%H:%M:%S"),
                'old_model': old_model,
                'new_model': self.model_name.upper(),
                'message': f"Model dynamically switched to {self.model_name.upper()}"
            }
            self._broadcast_event(event_obj)

            return {
                'success': True,
                'model': self.model_name.upper(),
                'old_model': old_model,
                'message': f"Active model successfully switched to {self.model_name.upper()}"
            }

    def get_flow_tables(self):
        """Returns flow tables for all switches (queried directly from Ryu REST when active)."""
        import urllib.request
        with self.lock:
            res = {}

            # First, check if Ryu REST API is reachable to get genuine OpenFlow 1.3 switch flow tables
            ryu_live = False
            try:
                req = urllib.request.Request("http://127.0.0.1:8080/stats/switches", headers={'User-Agent': 'SentiNex'})
                with urllib.request.urlopen(req, timeout=0.8) as resp:
                    if resp.status == 200:
                        dpids = json.loads(resp.read().decode())
                        for dpid in dpids:
                            sw_key = f"s{dpid}"
                            flow_url = f"http://127.0.0.1:8080/stats/flow/{dpid}"
                            with urllib.request.urlopen(flow_url, timeout=0.8) as f_resp:
                                flow_data = json.loads(f_resp.read().decode())
                                raw_rules = flow_data.get(str(dpid), [])
                                formatted_rules = []
                                for r in raw_rules:
                                    formatted_rules.append({
                                        'table_id': r.get('table_id', 0),
                                        'priority': r.get('priority', 0),
                                        'match': r.get('match', {}),
                                        'actions': r.get('actions', []),
                                        'packet_count': r.get('packet_count', 0),
                                        'byte_count': r.get('byte_count', 0),
                                        'idle_timeout': r.get('idle_timeout', 0),
                                        'hard_timeout': r.get('hard_timeout', 0),
                                        'rule_type': 'mitigation_drop' if r.get('priority') == 100 else ('table_miss' if r.get('priority') == 0 else 'forwarding'),
                                        'installed_at': datetime.now().strftime("%H:%M:%S")
                                    })
                                res[sw_key] = {
                                    'dpid': dpid,
                                    'switch': sw_key,
                                    'rules': formatted_rules,
                                    'rule_count': len(formatted_rules),
                                    'source': 'Ryu REST API (Live OpenFlow 1.3)'
                                }
                        if res:
                            ryu_live = True
            except Exception:
                pass

            if not ryu_live:
                # Fallback to local SentiNex flow table state
                for dpid, rules in self.flow_tables.items():
                    sw_key = f"s{dpid}"
                    res[sw_key] = {
                        'dpid': dpid,
                        'switch': sw_key,
                        'rules': rules,
                        'rule_count': len(rules),
                        'source': 'SentiNex Control Plane'
                    }

            return res

